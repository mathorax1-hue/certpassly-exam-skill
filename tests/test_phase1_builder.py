"""Public synthetic tests: builder pure functions (schema emission and README
provenance labels). Requires the pdf extra; skips cleanly on stdlib-only CI."""
import json
import os
import unittest

try:
    import fitz  # noqa: F401  (the real run needs it; guard mirrors production use)
    HAVE_FITZ = True
except ImportError:
    HAVE_FITZ = False

from certpassly.phase1 import build_structured_v1 as B


@unittest.skipUnless(HAVE_FITZ, "PyMuPDF (pdf extra) not installed")
class BuildSchemaTests(unittest.TestCase):
    def _cfg(self, **schema_overrides):
        sc = {"title": "synthetic title", "description": "synthetic description",
              "source_kind_extension": []}
        sc.update(schema_overrides)
        return {"schema": sc}

    def test_template_passthrough_when_no_overrides(self):
        tpl = os.path.join(os.path.dirname(os.path.abspath(B.__file__)),
                           "templates", "extraction-schema.v1.json")
        text, obj = B.build_schema(self._cfg(title=None, description=None))
        self.assertIsNone(obj)
        self.assertEqual(text, open(tpl, encoding="utf-8").read())

    def test_overrides_change_schema(self):
        text, obj = B.build_schema(self._cfg(title="synthetic title"))
        self.assertIsNotNone(obj)
        self.assertEqual(obj["title"], "synthetic title")
        self.assertEqual(json.loads(text)["title"], "synthetic title")

    def test_extension_declared_in_compatible_extensions(self):
        _, obj = B.build_schema(self._cfg(source_kind_extension=["typed_text_with_answer_image"]))
        ext_note = ", ".join(obj.get("compatible_extensions", []))
        self.assertIn("typed_text_with_answer_image", ext_note)
        enum = (obj["definitions"]["question_record"]["properties"]["answer"]
                ["properties"]["source_kind"]["enum"])
        self.assertIn("typed_text_with_answer_image", enum)


@unittest.skipUnless(HAVE_FITZ, "PyMuPDF (pdf extra) not installed")
class BuildReadmeTests(unittest.TestCase):
    STATS = {"pdf": {"sha256": "0" * 64, "bytes": 12345, "page_count": 9},
             "questions": 12, "pages": 9, "assets": 7, "usages": 8}

    def test_legacy_provenance_default_byte_compat(self):
        """With no provenance overrides the README must be byte-identical to the
        historical private-toolkit output for the same inputs."""
        cfg = {"exam_code": "SYN-001", "generated_by": {"worker": "Z.ai", "date": "2026-11-13",
                                                        "environment": "local sandbox"}}
        text = B.build_readme(cfg, self.STATS, {})
        self.assertIn(
            "Generated by the config-driven phase1-extraction toolkit "
            "(`tools/phase1-extraction/`, ZAI-EXTRACT-002) from the immutable "
            "owner source PDF.", text)
        self.assertIn("`tools/phase1-extraction/README.md` for the exact commands.", text)

    def test_provenance_override_labels(self):
        cfg = {"exam_code": "SYN-001",
               "generated_by": {"worker": "Z.ai", "date": "2026-11-13",
                                "environment": "local sandbox"},
               "provenance": {
                   "toolkit_label": "the public certpassly.phase1 toolkit (skill @ abc123)",
                   "commands_reference": "docs/PHASE1-EXTRACTION.md"}}
        text = B.build_readme(cfg, self.STATS, {})
        self.assertIn("Generated by the public certpassly.phase1 toolkit (skill @ abc123)",
                      text)
        self.assertIn("docs/PHASE1-EXTRACTION.md for the exact commands.", text)
        self.assertNotIn("tools/phase1-extraction", text)


if __name__ == "__main__":
    unittest.main()
